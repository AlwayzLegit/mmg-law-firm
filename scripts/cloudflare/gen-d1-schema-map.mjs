// Generates src/lib/db/d1Schema.generated.ts from migrations/d1/0001_schema.sql
// plus every "ALTER TABLE … ADD COLUMN" in the later numbered migrations
// (OPS-362, part 1 of OPS-353; ported from The Look a6db2f6). The D1 client reads it to decode
// rows the way PostgREST returns them (0/1 → booleans, JSON text →
// arrays/objects) and to resolve embedded selects such as
// "*, practice_areas(name)" through foreign keys.
//
//   node scripts/cloudflare/gen-d1-schema-map.mjs          # write the file
//   node scripts/cloudflare/gen-d1-schema-map.mjs --check  # exit 1 if stale (tests use this)

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseSchema } from "./d1-convert.mjs";

// The schema the Worker runs against is 0001_schema.sql plus the later
// numbered migrations, applied in order. Only "ALTER TABLE … ADD COLUMN"
// lines matter to the map (the D1 client rejects a select on a column it
// does not know, so a column added by 0005 without this went missing from
// /api/services on 2026-11-05).
export function loadMigrationSql(root) {
  const dir = join(root, "migrations/d1");
  return readdirSync(dir)
    .filter((f) => /^\d{4}_.*\.sql$/.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8"))
    .join("\n");
}

// Columns added after the CREATE TABLE statements, classified like
// parseSchema does (0/1 CHECK → bool, json_valid → json).
export function parseAddedColumns(sql) {
  const out = [];
  const re = /ALTER TABLE\s+([a-z_]+)\s+ADD COLUMN\s+([a-z_][a-z0-9_]*)\s+(?:TEXT|INTEGER|REAL|BLOB|NUMERIC)\b([^;]*);/gi;
  let m;
  while ((m = re.exec(sql))) {
    const [, table, name, rest] = m;
    let kind = "plain";
    if (new RegExp(`CHECK\\s*\\(\\s*${name}\\s+IN\\s*\\(\\s*0\\s*,\\s*1\\s*\\)\\s*\\)`, "i").test(rest)) kind = "bool";
    else if (new RegExp(`json_valid\\(\\s*${name}\\s*\\)`, "i").test(rest)) kind = "json";
    out.push({ table, name, kind });
  }
  return out;
}

// Foreign keys and primary keys, which parseSchema leaves out.
export function parseKeys(sql) {
  const out = {};
  const re = /CREATE TABLE IF NOT EXISTS\s+([a-z_]+)\s*\(([\s\S]*?)\n\);/g;
  let m;
  while ((m = re.exec(sql))) {
    const table = m[1];
    const fks = [];
    let pk = [];
    for (const raw of m[2].split("\n")) {
      const line = raw.replace(/--.*$/, "").trim();
      if (!line) continue;
      const inlineFk = /^([a-z_][a-z0-9_]*)\s+\w+.*?\bREFERENCES\s+([a-z_]+)\s*\(\s*([a-z_]+)\s*\)/i.exec(line);
      if (inlineFk && !/^(constraint|foreign)$/i.test(inlineFk[1])) fks.push({ column: inlineFk[1], table: inlineFk[2], refColumn: inlineFk[3] });
      const tableFk = /FOREIGN KEY\s*\(\s*([a-z_]+)\s*\)\s*REFERENCES\s+([a-z_]+)\s*\(\s*([a-z_]+)\s*\)/i.exec(line);
      if (tableFk) fks.push({ column: tableFk[1], table: tableFk[2], refColumn: tableFk[3] });
      const inlinePk = /^([a-z_][a-z0-9_]*)\s+\w+.*\bPRIMARY KEY\b/i.exec(line);
      if (inlinePk && !/^(constraint|primary)$/i.test(inlinePk[1])) pk = [inlinePk[1]];
      const tablePk = /^PRIMARY KEY\s*\(([^)]+)\)/i.exec(line);
      if (tablePk) pk = tablePk[1].split(",").map((s) => s.trim());
    }
    out[table] = { fks, pk };
  }
  return out;
}

export function buildSchemaMap(sql) {
  const keys = parseKeys(sql);
  const tables = {};
  for (const { table, columns } of parseSchema(sql)) {
    tables[table] = {
      columns: Object.fromEntries(columns.map((c) => [c.name, c.kind])),
      pk: keys[table]?.pk ?? [],
      fks: keys[table]?.fks ?? [],
    };
  }
  for (const { table, name, kind } of parseAddedColumns(sql)) {
    if (tables[table]) tables[table].columns[name] = kind;
  }
  return tables;
}

export function renderSchemaModule(map) {
  return `// GENERATED by scripts/cloudflare/gen-d1-schema-map.mjs from the
// numbered files in migrations/d1 — do not edit by hand. Re-run the
// script after changing the schema (tests fail while it is stale).

export type ColumnKind = "bool" | "json" | "plain";
export interface ForeignKey { column: string; table: string; refColumn: string }
export interface TableInfo { columns: Record<string, ColumnKind>; pk: string[]; fks: ForeignKey[] }

export const D1_SCHEMA: Record<string, TableInfo> = ${JSON.stringify(map, null, 2)};
`;
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop());
if (isMain) {
  const root = process.cwd();
  const sql = loadMigrationSql(root);
  const text = renderSchemaModule(buildSchemaMap(sql));
  const target = join(root, "src/lib/db/d1Schema.generated.ts");
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(target, "utf8").replace(/\r\n/g, "\n"); } catch {}
    if (current !== text) {
      console.error("src/lib/db/d1Schema.generated.ts is stale — run node scripts/cloudflare/gen-d1-schema-map.mjs");
      process.exit(1);
    }
    console.log("schema map up to date");
  } else {
    writeFileSync(target, text, "utf8");
    console.log(`wrote ${target} (${Object.keys(JSON.parse(JSON.stringify(buildSchemaMap(sql)))).length} tables)`);
  }
}
