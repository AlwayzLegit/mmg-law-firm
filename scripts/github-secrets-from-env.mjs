#!/usr/bin/env node
/**
 * Push the Cloudflare deploy secrets from .env.local to this repository's
 * GitHub Actions secrets with the `gh` CLI, so nobody pastes values by hand.
 *
 *   pnpm github-secrets            # push every key below that .env.local has
 *   pnpm github-secrets --dry-run  # only report which keys would be pushed
 *
 * Reads .env.local (never printed), skips keys that are missing or empty,
 * and never touches keys outside this list. Requires `gh auth login`.
 * The deploy workflow (.github/workflows/cloudflare-deploy.yml) forwards the
 * Worker secrets to Cloudflare with `wrangler secret bulk`.
 */
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync } from "node:fs";

const KEYS = [
  // Cloudflare (deploy)
  "CLOUDFLARE_API_TOKEN",
  "CLOUDFLARE_ACCOUNT_ID",
  // Worker runtime secrets
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "SUPABASE_SERVICE_ROLE_KEY",
  "RESEND_API_KEY",
  "RESEND_FROM_EMAIL",
  "LEAD_NOTIFY_EMAIL",
  "NEXT_PUBLIC_TURNSTILE_SITE_KEY",
  "TURNSTILE_SECRET_KEY",
  "CRON_SECRET",
  "REVALIDATE_SECRET",
  "ADMIN_API_KEY",
  "NEXT_PUBLIC_SENTRY_DSN",
];

const dryRun = process.argv.includes("--dry-run");
const file = ".env.local";
if (!existsSync(file)) {
  console.error(`No ${file} in the current directory.`);
  process.exit(1);
}

const env = Object.fromEntries(
  readFileSync(file, "utf8")
    .split(/\r?\n/)
    .filter((l) => l.includes("=") && !l.trimStart().startsWith("#"))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^['"]|['"]$/g, "")];
    }),
);

const gh = process.platform === "win32" && existsSync("C:/Program Files/GitHub CLI/gh.exe")
  ? "C:/Program Files/GitHub CLI/gh.exe"
  : "gh";

// Secrets that only need to be random and consistent between the Worker and
// the repo: generate once, append to .env.local so later runs reuse them.
for (const key of ["CRON_SECRET", "REVALIDATE_SECRET"]) {
  if (env[key]) continue;
  const value = randomBytes(32).toString("hex");
  env[key] = value;
  if (!dryRun) {
    appendFileSync(file, `\n# generated by scripts/github-secrets-from-env.mjs\n${key}=${value}\n`);
    console.log(`gen   ${key} (appended to ${file})`);
  } else {
    console.log(`would generate ${key}`);
  }
}

let pushed = 0;
for (const key of KEYS) {
  const value = env[key];
  if (!value) {
    console.log(`skip  ${key} (not in ${file})`);
    continue;
  }
  if (dryRun) {
    console.log(`would ${key} (${value.length} chars)`);
    continue;
  }
  execFileSync(gh, ["secret", "set", key], { input: value, stdio: ["pipe", "inherit", "inherit"] });
  console.log(`set   ${key}`);
  pushed += 1;
}
console.log(dryRun ? "dry run complete" : `${pushed} secret(s) pushed`);
