// Extracts the visible FAQ accordions from the rendered v3 pages and writes
// src/components/v3/v3-faqs-extracted.ts, which V3PageShell turns into
// FAQPage JSON-LD for pages the converter's own FAQ capture (v3-faqs.ts,
// lists of {q, a} in the design) does not cover — most guides and hubs build
// their FAQ markup by hand, so convert.mjs never sees them as data.
//
//   node tools/v3-design/extract-faqs.mjs http://localhost:3300
//
// Run it against a production build (`pnpm build && pnpm start`) from the
// repo root, after any converter run or FAQ copy edit. It needs Playwright:
// set PLAYWRIGHT_MODULE to its index.mjs if `playwright` isn't resolvable.
//
// A FAQ item is an accordion trigger whose state key names a FAQ
// (`…Faq…`, or `fqE<n>` on /accident-lawyer-faqs). Question = the trigger's
// text; answer = the panel it controls (aria-controls, else the region with
// the same key). Text comes from the DOM, so it matches what visitors see.

import fs from "node:fs";
import path from "node:path";

const base = (process.argv[2] ?? "http://localhost:3300").replace(/\/$/, "");
const ROOT = process.cwd();
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? "playwright");

const registry = fs.readFileSync(path.join(ROOT, "src/lib/v3/pages.ts"), "utf8");
const pages = [...registry.matchAll(/P\(\{\s*key:\s*"([^"]+)",\s*path:\s*"([^"]+)"/g)].map((m) => ({ key: m[1], path: m[2] }));
const covered = new Set(
  [...fs.readFileSync(path.join(ROOT, "src/components/v3/v3-faqs.ts"), "utf8").matchAll(/^ "(\w+)": \[/gm)].map((m) => m[1]),
);
const FAQ_KEY = /[Ff]aq|^fq[A-Z]/;

const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const page = await browser.newPage();
await page.route(/^https?:\/\/(?!localhost|127\.0\.0\.1)/, (r) => r.abort());
const out = {};
for (const p of pages) {
  if (covered.has(p.key)) continue;
  const file = path.join(ROOT, "src/components/v3/pages", `${p.key}.tsx`);
  if (!fs.existsSync(file)) continue;
  const keys = [...fs.readFileSync(file, "utf8").matchAll(/data-v3-aria="([^"]*)"/g)].map((m) => m[1]);
  if (!keys.some((k) => FAQ_KEY.test(k))) continue;
  const res = await page.goto(base + p.path, { waitUntil: "domcontentloaded" });
  if (!res || res.status() !== 200) throw new Error(`${p.path}: HTTP ${res?.status()}`);
  const items = await page.evaluate((src) => {
    const FAQ = new RegExp(src);
    const BLOCK = /^(P|DIV|LI|UL|OL|H[1-6]|BR|TR|TD|TH|SECTION|ARTICLE|BLOCKQUOTE)$/;
    const text = (root) => {
      let s = "";
      const walk = (n) => {
        if (n.nodeType === 3) return void (s += n.textContent);
        if (n.nodeType !== 1) return;
        if (n.getAttribute("aria-hidden") === "true" || /^(SVG|svg|SCRIPT|STYLE|IMG)$/.test(n.tagName)) return;
        const block = BLOCK.test(n.tagName);
        if (block) s += " ";
        n.childNodes.forEach(walk);
        if (block) s += " ";
      };
      walk(root);
      return s.replace(/\s+/g, " ").replace(/\s+([.,;:!?])/g, "$1").trim();
    };
    const seen = new Set();
    const items = [];
    for (const b of document.querySelectorAll(".v3-page [data-v3-aria]")) {
      const key = b.getAttribute("data-v3-aria");
      if (!FAQ.test(key) || seen.has(key)) continue;
      seen.add(key);
      const question = text(b).replace(/\s*[+−–-]$/, "").trim();
      const controlled = b.getAttribute("aria-controls");
      let panel = controlled ? document.getElementById(controlled) : null;
      if (!panel) {
        const regions = [...document.querySelectorAll(`[data-v3-r="${CSS.escape(key)}"]`)].filter((r) => !r.contains(b));
        panel = regions.sort((a, z) => text(z).length - text(a).length)[0] ?? null;
      }
      const answer = panel ? text(panel) : "";
      if (question && answer) items.push({ question, answer });
    }
    return items;
  }, FAQ_KEY.source);
  if (items.length) out[p.key] = items;
  console.log(`${p.key.padEnd(14)} ${String(items.length).padStart(2)} Q&A  ${p.path}`);
}
await browser.close();

fs.writeFileSync(
  path.join(ROOT, "src/components/v3/v3-faqs-extracted.ts"),
  `// Generated by tools/v3-design/extract-faqs.mjs from the rendered pages:
// visible FAQ accordions on v3 pages that v3-faqs.ts (converter) does not
// cover. Used for FAQPage JSON-LD. Re-run the tool after editing FAQ copy.
// TODO(human): attorney review required — mirrors the page copy.
import type { FaqItem } from "@/lib/data/faqs";

export const V3_FAQS_EXTRACTED: Record<string, FaqItem[]> = ${JSON.stringify(out, null, 1)};
`,
);
console.log(`wrote src/components/v3/v3-faqs-extracted.ts: ${Object.keys(out).length} pages, ${Object.values(out).flat().length} Q&A`);
